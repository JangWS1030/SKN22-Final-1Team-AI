from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from statistics import mean, median
from typing import Dict, List, Optional, Tuple

import cv2
import numpy as np
from skimage.metrics import structural_similarity

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from utils.manifest_paths import normalize_manifest_rows


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate hairstyle generation predictions against a benchmark manifest.")
    parser.add_argument(
        "--predictions-manifest",
        type=Path,
        required=True,
        help="JSONL generated by scripts/run_generation_benchmark.py",
    )
    parser.add_argument("--report-dir", type=Path, required=True)
    parser.add_argument("--bbox-pad", type=int, default=8)
    return parser.parse_args()


def load_jsonl(path: Path) -> List[Dict]:
    rows: List[Dict] = []
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return normalize_manifest_rows(rows, manifest_path=path)


def write_jsonl(path: Path, rows: List[Dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")


def read_rgb(path: str) -> np.ndarray:
    image_bgr = cv2.imread(path, cv2.IMREAD_COLOR)
    if image_bgr is None:
        raise FileNotFoundError(f"Could not read image: {path}")
    return cv2.cvtColor(image_bgr, cv2.COLOR_BGR2RGB)


def read_mask(path: Optional[str]) -> Optional[np.ndarray]:
    if not path:
        return None
    image = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
    if image is None:
        raise FileNotFoundError(f"Could not read mask: {path}")
    return (image > 127).astype(np.float32)


def crop_to_mask(
    prediction: np.ndarray,
    target: np.ndarray,
    mask: np.ndarray,
    pad: int,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    ys, xs = np.where(mask > 0.5)
    if len(xs) == 0 or len(ys) == 0:
        return prediction, target, mask
    y1 = max(0, int(ys.min()) - pad)
    y2 = min(mask.shape[0], int(ys.max()) + pad + 1)
    x1 = max(0, int(xs.min()) - pad)
    x2 = min(mask.shape[1], int(xs.max()) + pad + 1)
    return prediction[y1:y2, x1:x2], target[y1:y2, x1:x2], mask[y1:y2, x1:x2]


def masked_mae(prediction: np.ndarray, target: np.ndarray, mask: np.ndarray) -> float:
    mask3 = mask[..., None]
    denom = float(mask3.sum() * prediction.shape[2])
    if denom <= 0:
        return 0.0
    diff = np.abs(prediction.astype(np.float32) - target.astype(np.float32)) / 255.0
    return float((diff * mask3).sum() / denom)


def masked_psnr(prediction: np.ndarray, target: np.ndarray, mask: np.ndarray) -> float:
    mask3 = mask[..., None]
    denom = float(mask3.sum() * prediction.shape[2])
    if denom <= 0:
        return float("inf")
    diff = (prediction.astype(np.float32) - target.astype(np.float32)) / 255.0
    mse = float(((diff ** 2) * mask3).sum() / denom)
    if mse <= 1e-12:
        return float("inf")
    return 20.0 * math.log10(1.0 / math.sqrt(mse))


def masked_ssim(prediction: np.ndarray, target: np.ndarray, mask: np.ndarray, pad: int) -> float:
    pred_crop, target_crop, mask_crop = crop_to_mask(prediction, target, mask, pad)
    if pred_crop.shape[0] < 7 or pred_crop.shape[1] < 7:
        return 1.0
    mask3 = mask_crop[..., None]
    pred_norm = pred_crop.astype(np.float32) / 255.0
    target_norm = target_crop.astype(np.float32) / 255.0
    neutral = 0.5
    pred_masked = pred_norm * mask3 + neutral * (1.0 - mask3)
    target_masked = target_norm * mask3 + neutral * (1.0 - mask3)
    return float(structural_similarity(pred_masked, target_masked, channel_axis=2, data_range=1.0))


def safe_mean(values: List[float]) -> Optional[float]:
    return float(mean(values)) if values else None


def safe_median(values: List[float]) -> Optional[float]:
    return float(median(values)) if values else None


def summarize_metric(rows: List[Dict], key: str) -> Dict[str, Optional[float]]:
    values = [float(row[key]) for row in rows if row.get(key) is not None and math.isfinite(float(row[key]))]
    inf_count = sum(1 for row in rows if row.get(key) is not None and not math.isfinite(float(row[key])))
    return {
        "mean": safe_mean(values),
        "median": safe_median(values),
        "min": min(values) if values else None,
        "max": max(values) if values else None,
        "count": len(values),
        "inf_count": inf_count,
    }


def evaluate_row(row: Dict, pad: int) -> Dict:
    prediction = read_rgb(row["prediction_image_path"])
    target = read_rgb(row["target_image_path"])
    hair_mask = read_mask(row["mask_path"])
    face_mask = read_mask(row.get("face_protect_mask_path"))
    cloth_mask = read_mask(row.get("cloth_protect_mask_path"))

    if hair_mask is None:
        raise ValueError(f"Missing hair mask for {row['sample_id']}")

    metrics = {
        "sample_id": row["sample_id"],
        "benchmark_type": row.get("benchmark_type"),
        "hairstyle_id": row.get("hairstyle_id"),
        "style_domain": row.get("style_domain"),
        "hair_mae": masked_mae(prediction, target, hair_mask),
        "hair_psnr": masked_psnr(prediction, target, hair_mask),
        "hair_ssim": masked_ssim(prediction, target, hair_mask, pad),
        "overall_mae": masked_mae(prediction, target, np.ones_like(hair_mask, dtype=np.float32)),
        "face_preserve_mae": masked_mae(prediction, target, face_mask) if face_mask is not None else None,
        "cloth_preserve_mae": masked_mae(prediction, target, cloth_mask) if cloth_mask is not None else None,
        "hair_ratio": float(row.get("hair_ratio") or 0.0),
        "style_confidence": float(row.get("style_confidence") or 0.0),
        "prediction_image_path": row["prediction_image_path"],
    }
    return metrics


def build_markdown_report(summary: Dict) -> str:
    lines = [
        "# Hairstyle Generation Benchmark Report",
        "",
        f"- Prediction manifest: `{summary['predictions_manifest']}`",
        f"- Rows evaluated: `{summary['rows']}`",
        "",
        "## Core Metrics",
        "",
        f"- Hair MAE mean: `{summary['metrics']['hair_mae']['mean']:.4f}`" if summary["metrics"]["hair_mae"]["mean"] is not None else "- Hair MAE mean: `n/a`",
        f"- Hair PSNR mean: `{summary['metrics']['hair_psnr']['mean']:.2f}`" if summary["metrics"]["hair_psnr"]["mean"] is not None else "- Hair PSNR mean: `n/a`",
        f"- Hair SSIM mean: `{summary['metrics']['hair_ssim']['mean']:.4f}`" if summary["metrics"]["hair_ssim"]["mean"] is not None else "- Hair SSIM mean: `n/a`",
        f"- Face preserve MAE mean: `{summary['metrics']['face_preserve_mae']['mean']:.4f}`" if summary["metrics"]["face_preserve_mae"]["mean"] is not None else "- Face preserve MAE mean: `n/a`",
        f"- Cloth preserve MAE mean: `{summary['metrics']['cloth_preserve_mae']['mean']:.4f}`" if summary["metrics"]["cloth_preserve_mae"]["mean"] is not None else "- Cloth preserve MAE mean: `n/a`",
        "",
        "## Overfit Watch",
        "",
        "- Hair MAE should trend down while face/cloth preserve MAE remains flat or improves.",
        "- If hair metrics improve but face preserve MAE rises, the LoRA is memorizing texture at the cost of identity.",
        "- Compare smoke, recon, and edit runs with the same checkpoint before promoting a model.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    args = parse_args()
    rows = load_jsonl(args.predictions_manifest)
    report_dir = args.report_dir
    report_dir.mkdir(parents=True, exist_ok=True)

    per_sample = [evaluate_row(row, args.bbox_pad) for row in rows]
    write_jsonl(report_dir / "per_sample_metrics.jsonl", per_sample)

    summary = {
        "predictions_manifest": str(args.predictions_manifest),
        "rows": len(per_sample),
        "metrics": {
            "hair_mae": summarize_metric(per_sample, "hair_mae"),
            "hair_psnr": summarize_metric(per_sample, "hair_psnr"),
            "hair_ssim": summarize_metric(per_sample, "hair_ssim"),
            "overall_mae": summarize_metric(per_sample, "overall_mae"),
            "face_preserve_mae": summarize_metric(per_sample, "face_preserve_mae"),
            "cloth_preserve_mae": summarize_metric(per_sample, "cloth_preserve_mae"),
        },
    }
    (report_dir / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    (report_dir / "README.md").write_text(build_markdown_report(summary), encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
